using EyesOfHeavenDio;
using LocalModAudio;
using UnityEngine;
int checks=0;
void Check(bool value,string message){if(!value)throw new Exception(message);checks++;}
var owner=new Peer(false,true,true);var host=new Peer(true,true,false);var teammate=new Peer(false,true,false);
Harness.Select(owner);
var playback=DioAudioRelay.Emit(owner.owners[1],"barrage",1,false);
Check(playback && owner.plays==1 && owner.sent.Count==1,"Owner predicts exactly one cue and sends it to the host");
byte[] request=owner.sent[0].bytes;
Harness.Deliver(host,request);
Check(host.plays==1 && host.sent.Count==1,"Host hears and forwards a remote owner's cue");
Harness.Deliver(host,request);
Check(host.plays==1 && host.sent.Count==1,"Duplicate owner packets must not replay or relay");
byte[] broadcast=host.sent[0].bytes;
Harness.Deliver(owner,broadcast);Check(owner.plays==1,"Predicted owner must not hear its echo");
Harness.Deliver(teammate,broadcast);Harness.Deliver(teammate,broadcast);
Check(teammate.plays==1,"Other clients play a relayed cue only once");
Harness.Select(owner);UnityEngine.Object.Destroy(playback.gameObject);
Check(owner.sent.Count==2,"Interrupted playback sends a cancellation");
Harness.Deliver(host,owner.sent[1].bytes);
Check(host.stops==1 && host.sent.Count==2,"Host cancels remote playback and forwards cancellation");
Harness.Deliver(teammate,host.sent[1].bytes);Check(teammate.stops==1,"Teammate stops an interrupted long cue");
Harness.Select(host);DioAudioRelay.Emit(host.owners[1],"time-resume",1,true);
Check(host.plays==2,"Server event is audible to a host teammate");
Harness.Deliver(owner,host.sent[2].bytes);Check(owner.plays==2,"Remote owner hears server-origin time resume");
Harness.Deliver(teammate,host.sent[2].bytes);Check(teammate.plays==2,"Teammate hears the same server event");
Harness.Select(teammate);int before=teammate.sent.Count;
Check(DioAudioRelay.Emit(teammate.owners[1],"impact",1,false)==null && teammate.sent.Count==before,"Remote state replicas must not originate duplicate audio");
var dedicated=new Peer(true,false,false);Harness.Select(dedicated);
DioAudioRelay.Emit(dedicated.owners[1],"time-resume",1,true);
Check(dedicated.plays==0 && dedicated.sent.Count==1,"Dedicated host relays without an audio device");
Harness.Select(host);before=host.sent.Count;
Check(DioAudioRelay.Emit(host.owners[1],"unknown",1,true)==null && host.sent.Count==before,"Unknown cue is rejected");
Check(AudioMixRules.ListenerGain(true,true,0,.2f)==1,"Owner retains normal volume");
Check(Math.Abs(AudioMixRules.ListenerGain(false,true,0,.2f)-.2f)<.0001,"Nearby party volume defaults to 20 percent");
Check(AudioMixRules.ListenerGain(false,true,50,.2f)<.05f,"Distant teammates are attenuated");
Check(AudioMixRules.ListenerGain(false,true,80,.2f)==0,"Beyond 80m is silent");
Check(AudioMixRules.ListenerGain(false,false,0,1)==0,"Unrelated teams do not leak callouts");
Check(AudioMixRules.ListenerGain(false,true,float.NaN,1)==0,"Invalid listener distance is silent");
var sequence=new AudioSequence();Check(sequence.Accept(1)&&!sequence.Accept(1)&&sequence.Accept(3)&&!sequence.Accept(2),"Duplicate and stale cues cannot restart sounds");
Check(!sequence.Accept(0),"Zero sequence is rejected");
Console.WriteLine($"PASS: {checks} multiplayer relay, cancellation, dedicated-host, deduplication and mix checks (simulated transport).");
